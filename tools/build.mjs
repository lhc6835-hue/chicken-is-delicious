#!/usr/bin/env node
// Embeds the sound effects as data URIs (so the game also runs straight from file://) and bundles
// src/ into game.js with esbuild.  node tools/build.mjs [--watch]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(ROOT, "assets", "audio", "sfx");
const sfx = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".mp3")).sort()) {
  sfx[basename(f, ".mp3")] = "data:audio/mpeg;base64," + readFileSync(join(dir, f)).toString("base64");
}
writeFileSync(join(ROOT, "src", "sfxdata.js"), "// Generated by tools/build.mjs from assets/audio/sfx. Do not edit.\nexport const SFX = " + JSON.stringify(sfx) + ";\n");

const opts = { entryPoints: [join(ROOT, "src", "main.js")], bundle: true, format: "iife", target: "es2020", outfile: join(ROOT, "game.js"), minify: true, legalComments: "none" };
if (process.argv.includes("--watch")) {
  const ctx = await esbuild.context(opts);
  await ctx.watch();
  console.log("watching...");
} else {
  await esbuild.build(opts);
  console.log(`built game.js with ${Object.keys(sfx).length} sounds`);
}
